NEW NEW  docflow/internal/recognize/tablerows.go
NEW NEW  docflow/internal/recognize/review2_band_test.go
MANIFEST
[[ $bad -eq 0 ]] || { err "Ничего не изменено."; exit 1; }
echo "  ок"

BACKUP=".backup-review2fix3-$(date +%Y%m%d-%H%M%S)"
mkdir -p "$BACKUP"; : > "$BACKUP/.added"
while read -r a b path; do
  [[ -n "$path" ]] || continue
  if [[ -f "$path" ]]; then mkdir -p "$BACKUP/$(dirname "$path")"; cp -p "$path" "$BACKUP/$path"; else echo "$path" >> "$BACKUP/.added"; fi
