func linesSum(t *testing.T, ft *domain.FreeTable) (float64, int) {
	t.Helper()
	sum, n := 0.0, 0
	for _, l := range FreeTableToLines(ft) {
		v, err := strconv.ParseFloat(l.Amount, 64)
		if err != nil {
			t.Fatalf("позиция без суммы: %+v", l)
		}
		sum += v
		n++
	}
	return math.Round(sum*100) / 100, n
}

// IMG_0171: «Сумма НДС» и «Всего с НДС» выровнены по нижней строке ячейки.
func TestMultilineNumbersOnSecondRow(t *testing.T) {
	cols := []string{"Наименование работы (услуги)", "Ед. изм.", "Кол-во", "Цена, BYN", "Стоимость, BYN", "Ставка НДС, %", "Сумма НДС, BYN", "Всего с НДС, BYN"}
	ft := CleanFreeTable(freeTableForTest(cols, [][]string{
		{"( 23102 ) Электроэнергия \\ за август 2023 г.", "кВт.ч", "85.0000", "0.4044", "34.37", "20%", "", ""},
		{"", "", "", "", "", "", "6.87", "41.24"},
		{"(23102) Водоснабжение \\ за август 2023 г.", "м3", "0.5000", "2.3400", "1.17", "20%", "", ""},
		{"", "", "", "", "", "", "0.23", "1.40"},
		{"( 23102 ) Водоотведение \\ за август 2023 г.", "м3", "0.4130", "1.3801", "0.57", "20%", "", ""},
		{"", "", "", "", "", "", "0.12", "0.69"},
	}))
	if sum, n := linesSum(t, ft); n != 3 || sum != 43.33 {
		t.Fatalf("позиций %d, сумма %v; ожидалось 3 и 43.33: %v", n, sum, ft.Rows)
	}
}

// IMG_0144: адрес объекта над позицией, наименование на две строки, у
// последней позиции НДС и итог уехали на строку ниже, над таблицей — номера
// граф, разнесённые по строкам.
func TestMultilineAddressAndWrappedName(t *testing.T) {
	cols := []string{"", "измер.", "Кол-во", "Тариф", "всего без", "Ст. НДС", "Сумма НДС", "Стоимость"}
	ft := CleanFreeTable(freeTableForTest(cols, [][]string{
		{"", "", "2", "3", "4", "", "", "НДС, руб"},
		{"", "", "", "", "5", "", "", ""},
		{"Возмещение затрат по", "", "", "", "", "", "", "ул.Октябрская,8а"},
		{"электроэнергии (места общего пользования)", "кВт", "0.09", "0.33554", "0.03", "20%", "0.01", "0.04"},
		{"Возмещение затрат по электроэнергии (по", "кВт", "105", "0.40659", "42.69", "20%", "8.54", "51.23"},
		{"Возмещение затрат по", "", "", "", "", "ул.Кальварийская,9", "", "(административное)"},
		{"отдельно установленному прибору электрической", "кВт", "118", "0.40659", "47.98", "20%", "", ""},
		{"энергии)", "", "", "", "", "", "9.60", "57.58"},
	}))
	sum, n := linesSum(t, ft)
	if n != 3 || sum != 108.85 {
		t.Fatalf("позиций %d, сумма %v; ожидалось 3 и 108.85: %v", n, sum, ft.Rows)
	}
	lines := FreeTableToLines(ft)
	if !strings.Contains(lines[0].Name, "ул.Октябрская,8а") || !strings.HasPrefix(lines[0].Name, "Возмещение затрат по электроэнергии") {
		t.Fatalf("адрес или начало наименования потеряны: %q", lines[0].Name)
	}
	if !strings.HasSuffix(lines[2].Name, "энергии)") || !strings.Contains(lines[2].Name, "ул.Кальварийская,9") {
		t.Fatalf("наименование последней позиции собрано неверно: %q", lines[2].Name)
	}
}

// Две настоящие позиции без наименования у второй не склеиваются, если их
// числа не дают арифметику позиции.
func TestMultilineKeepsIndependentRows(t *testing.T) {
	cols := []string{"Наименование", "Кол-во", "Цена", "Сумма", "Сумма НДС", "Всего"}
	ft := CleanFreeTable(freeTableForTest(cols, [][]string{
		{"Услуга А", "2", "5.00", "10.00", "", ""},
		{"", "", "", "", "3.10", "7.77"},
	}))
	if len(ft.Rows) != 2 {
		t.Fatalf("склеены строки без подтверждения арифметикой: %v", ft.Rows)
	}
}

// Перенос наименования в накладной: «Артикул … надбавка» — хвост предыдущей
// позиции, а не начало следующей.
func TestMultilineTrailingArticle(t *testing.T) {
	cols := []string{"Наименование товара", "Ед.", "Количество", "Цена", "Стоимость", "Примечание"}
	ft := CleanFreeTable(freeTableForTest(cols, [][]string{
		{"Вкладыши коренные STD", "шт", "1", "70.99", "70.99", "Цена импортера"},
		{"Артикул H1065/5 STD надбавка 35%", "", "", "", "", "45.80 руб.; оптовая"},
		{"28х42х5 Сальник", "шт", "1", "14.10", "14.10", "Цена импортера"},
		{"распредвала . Артикул 073.890", "", "", "", "", "9.10 руб.; оптовая"},
	}))
	lines := FreeTableToLines(ft)
	if len(lines) != 2 || !strings.Contains(lines[0].Name, "H1065/5") || !strings.Contains(lines[1].Name, "распредвала") {
		t.Fatalf("хвосты наименований разложены неверно: %+v", lines)
	}
}

func TestMultilineSwitchOff(t *testing.T) {
	t.Setenv("TABLE_MULTILINE", "false")
	cols := []string{"Наименование", "Кол-во", "Цена", "Стоимость", "Сумма НДС", "Всего с НДС"}
	ft := CleanFreeTable(freeTableForTest(cols, [][]string{
		{"Электроэнергия", "85", "0.4044", "34.37", "", ""},
		{"", "", "", "", "6.87", "41.24"},
	}))
	if len(ft.Rows) != 2 {
		t.Fatalf("TABLE_MULTILINE=false должен оставлять строки как есть: %v", ft.Rows)
	}
}
