say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
err() { printf '\033[31m%s\033[0m\n' "$*" >&2; }

[[ -f docker-compose.yml && -f "$FILE" ]] || { err "Запускать из /opt/docflow-deploy"; exit 1; }

got="$(sha256sum "$FILE" | cut -d' ' -f1)"
if [[ "$got" != "$WANT" ]]; then
  err "$FILE не совпадает с версией после geometry-v2."
  err "Сначала наложите patch-recognition-geometry-v2.sh, либо пришлите файл."
  exit 1
fi

cp -p "$FILE" "$FILE.bak-lines-$STAMP"
say "Резервная копия: $FILE.bak-lines-$STAMP"

