#
# Патч правит ТОЛЬКО фронт: отметка убрана из списка полей и из формы ручного
# ввода, вместо неё показывается объяснение — что случилось и куда смотреть.
# Логика бэкенда не меняется: в выгрузке в 1С <MissingFields><Field>lines</Field>
# остаётся, Дмитрию менять ничего не нужно.
#
# Накладывать ПОСЛЕ patch-recognition-geometry-v2.sh.
#
#     cd /opt/docflow-deploy
#     bash patch-lines-marker.sh
# =============================================================================
set -euo pipefail

