// Опознание строки итога по арифметике не должно съедать обычные позиции.
//
// Правило «значения строки равны суммам предыдущих» опиралось на
// независимость граф, которой нет. Графы НДС и «всего с НДС» — линейные функции
// базовой суммы: если совпала база, они совпадут всегда, и одно случайное
// совпадение давало сразу три «подтверждения».

// Третья позиция случайно равна сумме двух предыдущих по ВСЕМ денежным графам.
// Так выглядит обычный счёт на аренду двух помещений плюс коммунальные услуги.
func TestRunningTotalDoesNotEatOrdinaryRow(t *testing.T) {
	ft := &domain.FreeTable{
		Columns: []string{"Наименование", "Сумма", "НДС", "Всего"},
		Roles:   []string{"name", "amount", "vat", "total"},
		Rows: [][]string{
			{"Аренда офиса", "100,00", "20,00", "120,00"},
			{"Аренда склада", "100,00", "20,00", "120,00"},
			{"Коммунальные услуги", "200,00", "40,00", "240,00"},
		},
	}
	takeGarbledTotalsRow(ft)
	if len(ft.Rows) != 3 {
		t.Fatalf("позиций осталось %d вместо 3 — обычная строка съедена как итог: %v", len(ft.Rows), ft.Rows)
	}
	if len(ft.Totals) != 0 {
		t.Errorf("итог выдуман из позиции: %q", strings.Join(ft.Totals, " "))
	}
}

// Графа «№ п/п» и графа количества складываются «бесплатно»: 3 = 1 + 2 и
// 2 = 1 + 1. Раньше этого хватало на два совпадения, и третья позиция
// нумерованной накладной выбрасывалась.
func TestServiceColumnsDoNotCountAsTotals(t *testing.T) {
	ft := &domain.FreeTable{
		Columns: []string{"№", "Наименование", "Кол-во", "Цена", "Сумма"},
		Roles:   []string{"number", "name", "qty", "price", "amount"},
		Rows: [][]string{
			{"1", "Товар А", "1", "10,00", "10,00"},
			{"2", "Товар Б", "1", "17,50", "17,50"},
			{"3", "Товар В", "2", "5,00", "10,00"},
		},
	}
	takeGarbledTotalsRow(ft)
	if len(ft.Rows) != 3 {
		t.Fatalf("позиций осталось %d вместо 3 — сработали служебные графы: %v", len(ft.Rows), ft.Rows)
	}
}

// Настоящий итог забирается, но только с конца таблицы и только по деньгам.
func TestRealTotalsRowTaken(t *testing.T) {
	ft := &domain.FreeTable{
		Columns: []string{"Наименование", "Сумма", "НДС", "Всего"},
		Roles:   []string{"name", "amount", "vat", "total"},
		Rows: [][]string{
			{"Услуга А", "10,00", "2,00", "12,00"},
			{"Услуга Б", "20,00", "4,00", "24,00"},
			{"Услуга В", "30,00", "6,00", "36,00"},
			{"ОТОТИ", "60,00", "12,00", "72,00"},
		},
	}
	takeGarbledTotalsRow(ft)
	if len(ft.Rows) != 3 {
		t.Fatalf("итоговая строка осталась в позициях, сумма документа удвоится: %v", ft.Rows)
	}
	if !strings.Contains(strings.Join(ft.Totals, " "), "72,00") {
		t.Errorf("итог не забран: %q", strings.Join(ft.Totals, " "))
	}
}

// Данные не пропадают: если числовой итог уже найден по слову, вторая
// подходящая строка остаётся позицией, а не исчезает молча.
func TestSecondCandidateStaysAsRow(t *testing.T) {
	ft := &domain.FreeTable{
		Columns: []string{"Наименование", "Сумма", "НДС", "Всего"},
		Roles:   []string{"name", "amount", "vat", "total"},
		Totals:  []string{"Итого", "60,00", "12,00", "72,00"},
		Rows: [][]string{
			{"Услуга А", "10,00", "2,00", "12,00"},
			{"Услуга Б", "20,00", "4,00", "24,00"},
			{"Услуга В", "30,00", "6,00", "36,00"},
		},
	}
	takeGarbledTotalsRow(ft)
	if len(ft.Rows) != 3 {
		t.Fatalf("строка исчезла при уже заполненном итоге: %v", ft.Rows)
	}
}
