# =============================================================================
# DocFlow — исправление 2 к patch-review2.sh (накладывать после patch-review2-fix1.sh)
#
# По логам проверяющего: правило про колонки («граница ячейки ставится, только
# если просвет повторяется в соседней строке») верно на сплошном тексте, но в
# таблице из-за шапки в две строки и пустых ячеек колонки не идут сплошняком,
# и правило их выбрасывало. На счёте рынка раскладка 9 сентября была на восемь
# колонок, после патча — на две.
#
# Теперь:
#   * правило про колонки действует только ВНЕ таблицы — текст актов читается
#     так же, как сейчас;
#   * внутри таблицы поиск колонок как было 9 сентября: разборщики таблиц по
#     раскладке получают раскладку движка без изменений, а в 04-ocr-layout.txt
#     полоса таблицы (вместе с шапкой в две строки и строкой «Всего») взята
#     строками движка;
#   * если полосу в раскладке движка найти не удалось, ячейки таблицы режутся
#     по каждому просвету, без проверки соседних строк.
#
# Сверка на 20 трассировках от 9 сентября: таблица, собранная по раскладке,
# совпадает с тогдашней на всех 20 документах (счёт рынка — снова 5 колонок
# по шапке и 8 ячеек в строке, как было).
#
#   cd /opt/docflow-deploy
#   bash patch-review2-fix2.sh             # применить и пересобрать бэкенд
#   bash patch-review2-fix2.sh --rollback  # вернуть состояние после fix1
# =============================================================================
set -euo pipefail
MODE=apply
for a in "$@"; do case "$a" in --rollback) MODE=rollback ;; --no-build) MODE=nobuild ;; *) echo "неизвестный ключ: $a"; exit 2 ;; esac; done
say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
err() { printf '\033[31m%s\033[0m\n' "$*" >&2; }
[[ -d docflow/internal/recognize && -f docker-compose.yml ]] || { err "Запускать из /opt/docflow-deploy"; exit 1; }
if docker compose version >/dev/null 2>&1; then DC="docker compose"; else DC="docker-compose"; fi

if [[ "$MODE" == rollback ]]; then
  last="$(ls -1d .backup-review2fix2-* 2>/dev/null | sort | tail -n1 || true)"
  [[ -n "$last" ]] || { err "Резервных копий .backup-review2fix2-* нет."; exit 1; }
  (cd "$last" && find . -type f ! -name .added -print0 | xargs -0 -I{} cp -p {} ../{})
  [[ -f "$last/.added" ]] && while read -r f; do [[ -n "$f" ]] && rm -f "$f"; done < "$last/.added"
  say "Возвращено из $last. Пересборка: $DC build docflow-backend && $DC up -d docflow-backend"
  exit 0
fi

say "Проверка версий"
bad=0
while read -r want path; do
  [[ -n "$path" ]] || continue
  [[ "$want" == NEW ]] && continue
  if [[ ! -f "$path" ]]; then err "  нет файла: $path"; bad=1; continue; fi
  got="$(sha256sum "$path" | cut -d' ' -f1)"
  [[ "$got" == "$want" ]] || { err "  не совпадает с версией после fix1: $path"; bad=1; }
done <<'MANIFEST'
df809594c62c79dc629d477f6134a1f898d79052b757c7ea51dfb23d61ce8a06  docflow/internal/recognize/pipeline.go
5fc55f896ebabd54d2d647cbb5c39fcaa7f567ea0f66df78f2f14001e1eaab6f  docflow/internal/recognize/review2_table_test.go
dc83406728034c7d4a3086220742484c85134f022b93bb421ba360ca39087692  docflow/internal/recognize/readorder.go
NEW  docflow/internal/recognize/testdata/market-invoice-layout-engine.txt
MANIFEST
if [[ $bad -ne 0 ]]; then
  err "Ничего не изменено. Сначала должны быть применены patch-review2.sh и patch-review2-fix1.sh."
  exit 1
fi
echo "  ок"

BACKUP=".backup-review2fix2-$(date +%Y%m%d-%H%M%S)"
mkdir -p "$BACKUP"; : > "$BACKUP/.added"
while read -r want path; do
  [[ -n "$path" ]] || continue
  if [[ -f "$path" ]]; then mkdir -p "$BACKUP/$(dirname "$path")"; cp -p "$path" "$BACKUP/$path"; else echo "$path" >> "$BACKUP/.added"; fi
done <<'MANIFEST'
