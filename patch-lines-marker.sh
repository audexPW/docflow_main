# =============================================================================
# DocFlow — доправка к патчу geometry-v2: убрать псевдополе «lines» из карточки.
#
# «lines» в recognition.missing — не реквизит, а отметка бэкенда о том, что
# сумма строк табличной части не сошлась с итогом документа. В этом случае
# позиции в 1С не отправляются (лучше без номенклатуры, чем с неверными
