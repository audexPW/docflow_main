// Пограничные случаи номера документа и строки итога.

// «бланков», «формированию» — это не слово-владелец чужого номера. Владелец —
// только «Форма № 868» / «бланк № 5», когда слово стоит прямо перед знаком.
func TestFormWordDoesNotWipeOwnNumber(t *testing.T) {
	cases := map[string]struct{ line, want string }{
		"акт списания бланков":    {"АКТ списания бланков строгой отчетности № 12", "12"},
		"формирование отчётности": {"Акт оказания услуг по формированию отчетности № 15", "15"},
		"бланк не перед знаком":   {"Акт списания бланка строгой отчетности № 12", "12"},
		"номер бланка — не номер": {"АКТ Форма № 868", ""},
		"номер формы без пробела": {"АКТ Форма №868", ""},
	}
	for name, c := range cases {
		if got := HeaderNumberFromWords(headerLine(c.line)); got != c.want {
			t.Errorf("%s: получено %q, ожидалось %q (строка %q)", name, got, c.want, c.line)
		}
	}
}

// «Лицевой счет № 123456» — реквизит, а не название документа.
func TestPersonalAccountIsNotTitle(t *testing.T) {
	ws := []wordBox{
		wb("Лицевой", 100, 100, 80), wb("счет", 190, 100, 45), wb("№", 245, 100, 12), wb("123456", 265, 100, 70),
		wb("АКТ", 900, 140, 40), wb("№", 950, 140, 12), wb("12", 970, 140, 20), wb("от", 1000, 140, 20), wb("30.09.2023", 1030, 140, 90),
	}
	if got := HeaderNumberFromWords(ws); got != "12" {
		t.Errorf("получено %q, ожидалось 12 — лицевой счёт принят за название документа", got)
	}
}

// Дата в строке «Всего по счёту от 14.09.2026» — не деньги: Totals не занят, и
// изуродованный итог должен быть забран.
func TestDateIsNotMoneyInTotals(t *testing.T) {
	cols := []string{"Наименование", "Сумма", "НДС", "Всего"}
	ft := &domain.FreeTable{
		Columns: cols,
		Roles:   rolesFor(cols),
		Totals:  []string{"Всего по счёту от 14.09.2026"},
		Rows: [][]string{
			{"Вода", "10,00", "2,00", "12,00"},
			{"Стоки", "20,65", "4,13", "24,78"},
			{"ИТ0ГО", "30,65", "6,13", "36,78"},
		},
	}
	takeGarbledTotalsRow(ft)
	if len(ft.Rows) != 2 {
		t.Errorf("дата в итоге сочтена деньгами, итог остался позицией: %q", ft.Rows)
	}
}

// Роли не определены: графы № и количества складываются «бесплатно» (3 = 1 + 2,
// 2 = 1 + 1). Неизвестная графа считается денежной, только если в этой строке
// сумма написана деньгами.
func TestUnknownRolesJudgeByContent(t *testing.T) {
	ft := &domain.FreeTable{
		Rows: [][]string{
			{"1", "Товар А", "1", "45,00", "45,00"},
			{"2", "Товар Б", "1", "45,00", "45,00"},
			{"3", "Товар В", "2", "45,00", "90,00"},
		},
	}
	takeGarbledTotalsRow(ft)
	if len(ft.Rows) != 3 {
		t.Errorf("позиция съедена через графы № и количества: %q", ft.Rows)
	}
}

// Двойной сдвиг: слово, опустившееся после поправки в следующую полосу, не
// должно получить вторую поправку. Лист с наклоном в «обратную» сторону
// (k < 0) — поправка опускает слова.
func TestDeskewNoDoubleShift(t *testing.T) {
	// «верх» и «низ» стоят у левого края (поправка им ноль) и задают полосы
	// [100, 260) и [260, 420): без «низа» вторая полоса не обрабатывается вовсе,
	// и двойной сдвиг проверить нечем.
	toks := []token{
		{Text: "верх", X0: 0, X1: 60, Y0: 100, Y1: 120},
		{Text: "низ", X0: 0, X1: 60, Y0: 400, Y1: 420},
	}
	const k = -0.03
	for x := 400.0; x <= 2000; x += 100 {
		y := 270 + k*x // 258 … 210: вся строка в первой полосе, после поправки — 270, во второй
		toks = append(toks, token{Text: "w", X0: x, X1: x + 60, Y0: y, Y1: y + 20})
	}
	out := deskewTokens(toks)
	for i, t2 := range out {
		if t2.Text != "w" {
			continue
		}
		if math.Abs(t2.Y0-270) > 1 {
			t.Fatalf("слово %d (x=%.0f) после поправки на y=%.1f, ожидалось 270 — сдвинуто дважды или не выпрямлено",
				i, t2.X0, t2.Y0)
		}
	}
}
