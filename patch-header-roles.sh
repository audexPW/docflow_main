# =============================================================================
# DocFlow — шапка таблицы: роли граф по подписи и по арифметике строк
#
# Накладывается после patch-multiline-number.sh.
#
# Позиции уже собраны верно, а сумма в 1С не уходит, потому что графе досталась
# не та роль. Что сделано (headerroles.go):
#   * подписи, разорванные переносом («Коли- чество», «изме- рения», «мость»)
#     и испорченные OCR («Стоимось», «нлс»), узнаются;
#   * «с НДС», «всего с учетом НДС», «Стоимость … НДС, руб» — итог по строке,
#     а не сумма налога; «НДС, руб. всего без» — сумма без налога;
#   * вторая строка шапки, попавшая в данные («Сумма | НДС | Всего с НДС»),
#     дописывается к подписям граф;
#   * если по подписям строка не сходится, а среди граф есть три, где
#     «без НДС + НДС = с НДС» копейка в копейку, роли ставятся по цифрам;
#   * наименование ищется по содержимому, если графа «Наименование» пустая
#     (данные сдвинуты на графу вправо);
#   * «23,54 Итого» не в начале строки и итог без слова «Итого» больше не
#     становятся позицией;
#   * сумма без НДС документа берётся из позиций, только если позиции
#     сходятся с итогом (иначе обрывок таблицы затирал верную сумму из текста).
# TABLE_HEADER_FIX=false — прежнее поведение.
#
# Тесты (headerroles_test.go): подписи граф с реальных бланков; 12 настоящих
# таблиц из трассировок (testdata/tables) — у каждой позиции своя сумма,
# без НДС + НДС = с НДС в каждой строке, итог равен итогу документа.
#
# Замер по трассировкам 15.09: позиции не сходятся с итогом — 9 из 20
# (было 15 после прошлого патча, 19 до него).
#
#   cd /opt/docflow-deploy
#   bash patch-header-roles.sh             # применить и пересобрать бэкенд
#   bash patch-header-roles.sh --no-build  # разложить и прогнать тесты
#   bash patch-header-roles.sh --rollback  # вернуть как было
#   bash patch-multiline-number.sh --replay  # замер по ./trace
# =============================================================================
