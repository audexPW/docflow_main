#!/usr/bin/env bash
# =============================================================================
# DocFlow — позиции в несколько строк и номер с бланка
#
# Накладывается поверх текущего /opt/docflow-deploy (после audex-recognize.patch).
#
# 1. Сборка позиций, напечатанных в несколько строк (multiline.go).
#    Адрес объекта над позицией, перенос наименования, «Сумма НДС» и «Всего
#    с НДС» на строке ниже количества и цены — раньше это были отдельные
#    «позиции», и сумма строк не сходилась с итогом. Обрывки склеиваются,
#    только если это подтверждает арифметика самого документа:
#      * строка с числами без своего наименования приклеивается к позиции
#        выше, если числа стоят в других графах и вместе дают
#        «без НДС + НДС = с НДС» или «кол-во × цена = сумма»;
#      * строка без чисел идёт к следующей позиции, если та начинается с
#        середины фразы (или стоит прямо под ней без наименования), иначе —
#        к предыдущей; адрес из графы суммы уходит в наименование;
#      * выше первой строки с деньгами ничего не склеивается (номера граф).
#    TABLE_MULTILINE=false — прежнее поведение.
#
# 2. Номер документа (numberpick.go). Если номер по месту на листе найден и
#    модель или правила прочитали другой — берётся бланк, в заметке к полю
#    остаётся прочитанное. NUMBER_PREFER_BLANK=false — прежнее поведение.
#
# 3. Повтор разбора по трассировкам без OCR и модели (replay_test.go):
#      bash patch-multiline-number.sh --replay            # каталог ./trace
#      bash patch-multiline-number.sh --replay /path/dir
#
# Замер на 73 трассировках (49 разных документов), до → после:
#   IMG_0144 136.37 (было 184.35), IMG_0171 43.33 (36.11), IMG_0138 0.19,
#   IMG_0140 0.42, IMG_0143 от 11.09 214.64 — сумма позиций сошлась с итогом;
#   ошибка «номер» 5 → 1 документ (IMG_0122 322, IMG_0169 666,
#   IMG_0206 2194-23/1, IMG_0004.pdf 0357107).
#
#   cd /opt/docflow-deploy
#   bash patch-multiline-number.sh             # применить и пересобрать бэкенд
#   bash patch-multiline-number.sh --no-build  # разложить и прогнать тесты
#   bash patch-multiline-number.sh --rollback  # вернуть как было
# =============================================================================
set -euo pipefail
MODE=apply
REPLAY_DIR=trace
while [[ $# -gt 0 ]]; do
  case "$1" in
    --rollback) MODE=rollback ;;
    --no-build) MODE=nobuild ;;
    --replay) MODE=replay; if [[ -n "${2:-}" && "${2:0:2}" != "--" ]]; then REPLAY_DIR="$2"; shift; fi ;;
    *) echo "неизвестный ключ: $1"; exit 2 ;;
  esac
  shift
done
say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
err() { printf '\033[31m%s\033[0m\n' "$*" >&2; }
[[ -d docflow/internal/recognize && -f docker-compose.yml ]] || { err "Запускать из /opt/docflow-deploy"; exit 1; }
if docker compose version >/dev/null 2>&1; then DC="docker compose"; else DC="docker-compose"; fi
GO_IMG=golang:1.22-bookworm
R=docflow/internal/recognize
NEW_FILES="$R/multiline.go $R/multiline_test.go $R/numberpick.go $R/numberpick_test.go $R/replay_test.go"

gotest() {
  docker run --rm -v "$PWD":/w -w /w/docflow -e GOFLAGS=-buildvcs=false "$@"
}

if [[ "$MODE" == rollback ]]; then
  last="$(ls -1d .backup-multiline-* 2>/dev/null | sort | tail -n1 || true)"
  [[ -n "$last" ]] || { err "Резервных копий .backup-multiline-* нет."; exit 1; }
  cp -p "$last/pipeline.go" "$R/pipeline.go"
  cp -p "$last/quality.go" "$R/quality.go"
  rm -f $NEW_FILES
  say "Возвращено из $last. Пересборка: $DC build docflow-backend && $DC up -d docflow-backend"
  exit 0
fi

if [[ "$MODE" == replay ]]; then
  [[ -f "$R/replay_test.go" ]] || { err "Патч ещё не применён."; exit 1; }
  dir="$(cd "$REPLAY_DIR" && pwd)"
  say "Повтор разбора по $dir"
  gotest -v "$dir":/trace:ro -e DOCFLOW_REPLAY=/trace ${TABLE_MULTILINE:+-e TABLE_MULTILINE=$TABLE_MULTILINE} ${NUMBER_PREFER_BLANK:+-e NUMBER_PREFER_BLANK=$NUMBER_PREFER_BLANK} $GO_IMG \
    sh -c 'go test ./internal/recognize/ -run TestReplayTraces -v -count=1 2>&1 | grep -E "итог=|документов|FAIL|panic"'
  exit 0
fi

say "Проверка версий"
bad=0
check() { # путь, допустимые хэши...
  local path="$1"; shift
  local got; got="$(sha256sum "$path" | cut -d' ' -f1)"
  for h in "$@"; do [[ "$got" == "$h" ]] && return 0; done
  err "  не та версия: $path"; bad=1
}
check "$R/pipeline.go" 2b8973abbf7e372af770ff6b1933d35197e95e59779849cbd8113771ea0b7750 e25e91716c4eb0f55a9175eaa6d43ed6fa46fb3e2fe0a8732685a163dc3fe835
check "$R/quality.go"  b342301ab0a8b7aa0854c1bfb7fbc285a41e83d5402b579eaf21672ba42bf854 543c734119e680cf3eb9f1a8af02aca847036fb4ad2612e6a8d7b7b93bcf6649
[[ $bad == 0 ]] || { err "Файлы отличаются от архива 15.09 — патч не накладываю, ничего не изменено."; exit 1; }

already=0
[[ "$(sha256sum "$R/pipeline.go" | cut -d' ' -f1)" == e25e91716c4eb0f55a9175eaa6d43ed6fa46fb3e2fe0a8732685a163dc3fe835 ]] && already=1
if [[ $already == 0 ]]; then
  bk=".backup-multiline-$(date +%Y%m%d-%H%M%S)"
  mkdir -p "$bk"
  cp -p "$R/pipeline.go" "$R/quality.go" "$bk/"
  say "Резервная копия: $bk"
else
  say "Патч уже был применён — перезаписываю теми же файлами"
fi

