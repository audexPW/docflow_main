#!/usr/bin/env bash
# =============================================================================
# DocFlow — исправление 3: таблица узнаётся по строкам, а не только по шапке
#
# Накладывается после patch-review2.sh и patch-review2-fix2.sh (fix1 не нужен,
# но и не мешает).
#
# Замечание проверяющего от 11.09: где таблица узнана, колонки вернулись как
# 9-го, но на счетах ЖКХ по общежитию и 370 таблицу не узнало — шапка в две
# строки, скан под углом, строка с УНП влезает в заголовок, и по одной чистой
# строке заголовка таблицу не поймать. Правило про колонки такие страницы
# по-прежнему резало, и они были хуже, чем 9-го.
#
# Что сделано:
#   * если шапку опознать не удалось, таблица ищется по самим строкам: три и
#     больше чисел, стоящих по колонкам, — это ряд таблицы и без шапки.
#     Колонки сверяются с допуском в несколько символов, поэтому скан под
#     углом не мешает; строка без чисел внутри полосы допустима (перенос
#     наименования на вторую строку);
#   * границы: сверху полоса доводится до подписей граф (до двух строк —
#     шапка в две строки), снизу заканчивается строкой «Итого». Текст
#     договора сверху и сумма прописью снизу в таблицу не попадают;
#   * строка с числами (та самая с УНП) больше не может стать шапкой: если
#     она попала в заголовок полосы, её отрезает. Это работает и там, где
#     шапка нашлась обычным способом.
#
# Полоса, найденная по шапке, не меняется — у неё поправлен только верх.
# Сверка на 20 трассировках от 9 сентября: таблицы совпадают с тогдашними,
# изменились только верхние границы на двух документах.
#
#   cd /opt/docflow-deploy
#   bash patch-review2-fix3.sh             # применить и пересобрать бэкенд
#   bash patch-review2-fix3.sh --rollback  # вернуть как было до этого файла
# =============================================================================
set -euo pipefail
MODE=apply
for a in "$@"; do case "$a" in --rollback) MODE=rollback ;; --no-build) MODE=nobuild ;; *) echo "неизвестный ключ: $a"; exit 2 ;; esac; done
say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
err() { printf '\033[31m%s\033[0m\n' "$*" >&2; }
[[ -d docflow/internal/recognize && -f docker-compose.yml ]] || { err "Запускать из /opt/docflow-deploy"; exit 1; }
if docker compose version >/dev/null 2>&1; then DC="docker compose"; else DC="docker-compose"; fi

if [[ "$MODE" == rollback ]]; then
  last="$(ls -1d .backup-review2fix3-* 2>/dev/null | sort | tail -n1 || true)"
  [[ -n "$last" ]] || { err "Резервных копий .backup-review2fix3-* нет."; exit 1; }
  (cd "$last" && find . -type f ! -name .added -print0 | xargs -0 -I{} cp -p {} ../{})
  [[ -f "$last/.added" ]] && while read -r f; do [[ -n "$f" ]] && rm -f "$f"; done < "$last/.added"
  say "Возвращено из $last. Пересборка: $DC build docflow-backend && $DC up -d docflow-backend"
  exit 0
fi

grep -q "engineTableBlock" docflow/internal/recognize/readorder.go 2>/dev/null \
  || { err "Сначала нужен patch-review2-fix2.sh."; exit 1; }

say "Проверка версий"
bad=0
while read -r a b path; do
  [[ -n "$path" ]] || continue
  [[ "$a" == NEW ]] && continue
  if [[ ! -f "$path" ]]; then err "  нет файла: $path"; bad=1; continue; fi
  got="$(sha256sum "$path" | cut -d' ' -f1)"
  [[ "$got" == "$a" || "$got" == "$b" ]] || { err "  не совпадает с версией после fix2: $path"; bad=1; }
done <<'MANIFEST'
