# =============================================================================
# DocFlow — исправление 4: при ошибках распознавания XML не формируется
#
# Накладывается после patch-review2-fix3.sh.
#
# Требование заказчика от 13.09.2026 (по документу IMG_0207, который получил
# «На согласовании у главбуха» с ошибками распознавания): при наличии ошибок
# распознавания статус не должен позволять сформировать файл XML. Главбух
# отправляет данные пакетом, поэтому плохо распознанный документ должен иметь
# статус «На проверке».
#
# Что сделано:
#   * ошибки распознавания отделены от деловых проверок. Ошибки — обязательное
#     поле не найдено, значение отклонено проверкой формата, уверенность ниже
#     порога, тип не определён, суммы или позиции не сходятся с итогом.
#     Незнакомый контрагент и неподтверждённый итог ошибкой не считаются: это
#     повод показать документ главбуху, а не вернуть его;
#   * документ с ошибками распознавания получает «На проверке». Он не уходит
#     в 1С, не попадает на согласование и не ставится в очередь на выгрузку;
#   * частичная выгрузка (ExportKindPartial) по умолчанию выключена: раньше
#     недораспознанный документ сразу формировал XML с тем, что нашлось.
#     Прежнее поведение возвращается ключом EXPORT_PARTIAL_ENABLED=true;
#   * согласовать документ с ошибками распознавания нельзя: кнопка вернёт
#     «исправьте поля, затем согласуйте»;
#   * в карточке сверху красная плашка со списком полей, из-за которых
#     документ не выгружается.
#
# После исправления полей документ идёт обычным путём: все обязательные поля
# на месте — «Подтверждён» и очередь в 1С (или согласование главбухом, если
# оно включено у компании).
#
#   cd /opt/docflow-deploy
#   bash patch-review2-fix4.sh             # применить и пересобрать
#   bash patch-review2-fix4.sh --rollback  # вернуть как было до этого файла
# =============================================================================
set -euo pipefail
