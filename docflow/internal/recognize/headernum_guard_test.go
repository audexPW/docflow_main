// Номер документа: чужой номер хуже пустого поля.
//
// Сценарии взяты из разбора 14.09 — каждый был проверен прогоном «до/после» и
// каждый портил поле номера после правок 13.09.

// headerLine собирает строку из слов, раскладывая их по горизонтали подряд.
func headerLine(text string) []wordBox {
	var out []wordBox
	x := 100.0
	for _, w := range strings.Fields(text) {
		width := float64(len([]rune(w))) * 12
		out = append(out, wb(w, x, 100, width))
		x += width + 12
	}
	// без второй строки разбор не состоится: нужен хотя бы ещё один ряд
	out = append(out, wb("Исполнитель", 100, 200, 120))
	out = append(out, wb("ООО", 240, 200, 40))
	return out
}

func TestHeaderNumberNotTaken(t *testing.T) {
	cases := map[string]string{
		"день из даты":             "СЧЕТ-ФАКТУРА от 11 Августа 2023 г.",
		"день из даты, акт":        "АКТ от 11 августа 2023 года",
		"номер чужого счёта":       "Акт выполненных работ к счету № 45",
		"номер чужой накладной":    "Акт приема товара к накладной № 771",
		"номер спецификации":       "Акт сдачи-приемки согласно спецификации № 3",
		"номер договора за фразой": "Акт выполненных работ по договору аренды от 01.03.2022г. №42",
		"пометка б/н":              "Акт выполненных работ б/н от 30.09.2023",
		"год с буквой":             "АКТ выполненных работ от 2024г.",
		"период вместо номера":     "АКТ за период 09.2023",
	}
	for name, line := range cases {
		got := HeaderNumberFromWords(headerLine(line))
		if got != "" {
			t.Errorf("%s: в поле номера уехало %q из строки %q — чужой номер хуже пустого поля", name, got, line)
		}
	}
}

func TestHeaderNumberTaken(t *testing.T) {
	cases := map[string]struct{ line, want string }{
		"серия буквами":        {"АКТ оказанных услуг № АП4531279 от 14.09.2023", "АП4531279"},
		"месяц словами рядом":  {"Счет-фактура № 85906 от 11 Августа 2023 г.", "85906"},
		"договор как документ": {"Договор оказания услуг № А769у от 22 августа 2023 г.", "А769у"},
		"составное название":   {"Счет-акт на оплату аренды № А0000000860", "А0000000860"},
	}
	for name, c := range cases {
		got := HeaderNumberFromWords(headerLine(c.line))
		if got != c.want {
			t.Errorf("%s: получено %q, ожидалось %q (строка %q)", name, got, c.want, c.line)
		}
	}
}
